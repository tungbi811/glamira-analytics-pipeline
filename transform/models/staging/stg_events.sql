SELECT
    _id                                                           AS event_id,
    collection                                                    AS event_name,
    TIMESTAMP_SECONDS(SAFE_CAST(time_stamp AS INT64))             AS event_time,
    SAFE.PARSE_DATETIME('%Y-%m-%d %H:%M:%S', local_time)          AS local_time,
    device_id,
    NULLIF(user_id_db, '')                                        AS user_id,
    NULLIF(email_address, '')                                     AS email_address,
    ip,
    user_agent,
    resolution,
    store_id,
    api_version,
    current_url,
    referrer_url,
    product_id,
    viewing_product_id,
    cat_id                                                        AS category_id,
    option,
    {{ parse_price('price') }}                                    AS price,
    NULLIF(currency, '')                                          AS currency_symbol,
    SAFE_CAST(is_paypal AS BOOL)                                  AS is_paypal,
    order_id,
    cart_products,
    SAFE_CAST(show_recommendation AS BOOL)                        AS is_recommendation_shown,
    recommendation,
    recommendation_product_id,
    SAFE_CAST(recommendation_clicked_position AS INT64)           AS recommendation_clicked_position,
    SAFE_CAST(recommendation_product_position AS INT64)           AS recommendation_product_position,
    NULLIF(utm_source, 'false')                                   AS utm_source,
    NULLIF(utm_medium, 'false')                                   AS utm_medium,
    NULLIF(key_search, '')                                        AS search_keyword,
    collect_id
FROM {{ source('raw', 'summary') }}